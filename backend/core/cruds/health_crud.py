from datetime import datetime, timezone
from typing import Optional
from sqlalchemy.orm import Session
from backend.core import logger
from backend.core.models.health_model import HealthCheckRecord, ServiceStatus

logging = logger(__name__)


class HealthCRUD:
    """
    Persistence operations for service diagnostics and heartbeat telemetry records.
    """

    @staticmethod
    def record_heartbeat(
        db: Session,
        service_name: str = "heatsafe-backend",
        status: ServiceStatus = ServiceStatus.HEALTHY,
    ) -> HealthCheckRecord:
        """
        Persist a new heartbeat execution record to the database.

        Args:
            db (Session): Active database session.
            service_name (str): Label identifying the service component.
            status (ServiceStatus): Operational status enumeration.

        Returns:
            HealthCheckRecord: Saved model instance with autogenerated identifier.

        Raises:
            Exception: Re-raises database write exceptions.
        """
        logging.info("Executing HealthCRUD.record_heartbeat")
        try:
            record = HealthCheckRecord(
                service_name=service_name,
                status=status.value,
                checked_at=datetime.now(timezone.utc),
            )
            db.add(record)
            db.commit()
            db.refresh(record)
            return record
        except Exception as err:
            logging.error(f"Error in HealthCRUD.record_heartbeat: {err}")
            db.rollback()
            raise err

    @staticmethod
    def get_latest_heartbeat(db: Session) -> Optional[HealthCheckRecord]:
        """
        Retrieve the most recent heartbeat record persisted in storage.

        Args:
            db (Session): Active database session.

        Returns:
            Optional[HealthCheckRecord]: Latest record or None if collection empty.

        Raises:
            Exception: Re-raises database query exceptions.
        """
        logging.info("Executing HealthCRUD.get_latest_heartbeat")
        try:
            return db.query(HealthCheckRecord).order_by(HealthCheckRecord.id.desc()).first()
        except Exception as err:
            logging.error(f"Error in HealthCRUD.get_latest_heartbeat: {err}")
            raise err
